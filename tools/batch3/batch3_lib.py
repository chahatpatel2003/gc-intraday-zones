def feature_table(D, zones, ep, events, all_b2_zones):
    zm = zones.set_index("zid")
    hist = inside_history(ep)
    byfam = {}
    for fam, zf in all_b2_zones.items():
        byfam[fam] = (B.zones_by_day(zf, D), zf["L"].to_numpy(), zf["H"].to_numpy(),
                      zf["act"].to_numpy(), zf["exp"].to_numpy())
    rows = []
    for e in events.itertuples(index=False):
        z = zm.loc[e.zid]
        mid = 0.5 * (z["L"] + z["H"])
        a = e.adr
        ia = int(np.searchsorted(D.ts, z["act"], "left"))
        iw = min(ia + 60, D.seg_end[ia] if ia < len(D.ts) else ia)
        dep60 = float(np.max(np.abs(D.c[ia:iw + 1] - mid)) / a) if iw > ia else np.nan
        t30 = min(ia + 30, iw)
        clean_dep = not np.any((D.h[ia:t30 + 1] >= z["L"]) & (D.l[ia:t30 + 1] <= z["H"]))
        dist_bt = float(np.max(np.abs(D.c[ia:e.T0 + 1] - mid)) / a) if e.T0 > ia else 0.0
        i5 = e.T0 - 5
        appr = (abs(np.log(D.c[e.T0 - 1] / D.c[i5 - 1])) / a
                if i5 - 1 >= D.seg_start[e.T0] else np.nan)
        conf = 0
        for fam, (bd, L_, H_, A_, X_) in byfam.items():
            if fam == e.fam:
                continue
            for ci in bd.get(int(e.day), []):
                if A_[ci] <= e.t0_ns < X_[ci] and L_[ci] <= e.P0 <= H_[ci]:
                    conf += 1
                    break
        rows.append({"zid": e.zid, "year": e.year, "sess": e.sess,
                     "age_min": e.age_min, "w_adr": e.W / a,
                     "prior_touches": e.touch_idx - 1,
                     "prior_inside": int(z_has_prior(hist, e.zid, e.T0)),
                     "dep60_adr": dep60, "clean_dep": int(clean_dep),
                     "dist_before_touch_adr": dist_bt, "approach_speed_adr": appr,
                     "approach_dir": e.side,
                     "sharp": float(z["sharp"]) if "sharp" in z.index else np.nan,
                     "fvr": float(z["fvr"]) if "fvr" in z.index else np.nan,
                     "confluence_n": conf,
                     "nf60_adr": (e.FE60 - e.AE60) / a})
    return pd.DataFrame(rows)


def binned_report(ft, feats):
    out = {}
    v = ft.dropna(subset=["nf60_adr"])
    for f in feats:
        s = v.dropna(subset=[f])
        if s[f].nunique() <= 2:
            g = s.groupby(s[f])["nf60_adr"]
            out[f] = {str(k): [int(c), round(float(m), 4)]
                      for k, (c, m) in zip(g.count().index, zip(g.count(), g.mean()))}
        else:
            try:
                q = pd.qcut(s[f], 3, duplicates="drop")
                g = s.groupby(q, observed=True)["nf60_adr"]
                out[f] = {str(k): [int(c), round(float(m), 4)]
                          for k, c, m in zip(g.count().index, g.count(), g.mean())}
            except ValueError:
                out[f] = "degenerate"
    return out
