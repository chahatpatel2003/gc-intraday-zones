NS_MIN = 60_000_000_000


def _hist_full(vals_lo, vals_hi, weights):
    p0 = vals_lo.min()
    i_lo = np.round((vals_lo - p0) / B.TICK).astype(int)
    i_hi = np.round((vals_hi - p0) / B.TICK).astype(int)
    hist = np.zeros(i_hi.max() + 1)
    for a, b, w in zip(i_lo, i_hi, weights):
        hist[a:b + 1] += w / (b - a + 1)
    poc = int(np.argmax(hist))
    tot = hist.sum()
    lo_i = hi_i = poc
    cum = hist[poc]
    while cum < 0.70 * tot:
        left = hist[lo_i - 1] if lo_i > 0 else -1.0
        right = hist[hi_i + 1] if hi_i < len(hist) - 1 else -1.0
        if right >= left:
            hi_i += 1; cum += hist[hi_i]
        else:
            lo_i -= 1; cum += hist[lo_i]
    return p0, hist, lo_i, hi_i


def gen_zon012_inst(D):
    """Instrumented twin of batch2_lib.gen_zon012 — identical zones + sharp/fvr meta."""
    rows, sharps, fvrs = [], [], []
    dd = Z._GenDedup()
    n = len(D.ts)
    wsums = deque(maxlen=20)
    snaps = np.flatnonzero(D.sm % 60 == 59)
    for i in snaps:
        d = D.day[i]
        a = D.adr[d]
        if not np.isfinite(a) or i - 359 < D.seg_start[i]:
            continue
        m = slice(i - 359, i + 1)
        p0, hist, lo_i, hi_i = _hist_full(D.l[m], D.h[m], D.v[m])
        wsum = float(D.v[m].sum())
        fvr = wsum / np.median(wsums) if len(wsums) == 20 else np.nan
        wsums.append(wsum)
        val, vah = p0 + lo_i * B.TICK, p0 + hi_i * B.TICK
        n10 = max(int(round(0.10 * a / B.TICK)), 1)
        act = D.ts[i] + NS_MIN
        exp = D.ts[min(i + 240, n - 1)] + NS_MIN
        half = 0.05 * a
        seg = D.iid[i]
        for ref, tag, edge_i, sgn in ((vah, "upperVA", hi_i, +1), (val, "lowerVA", lo_i, -1)):
            if abs(ref - D.c[i]) < 0.05 * a:
                continue
            L, H = ref - half, ref + half
            if dd.ok(L, H, act, exp):
                if sgn > 0:
                    inside = hist[max(edge_i - n10 + 1, 0):edge_i + 1]
                    outside = hist[edge_i + 1:edge_i + 1 + n10]
                else:
                    inside = hist[edge_i:edge_i + n10]
                    outside = hist[max(edge_i - n10, 0):edge_i]
                sh = (inside.mean() / max(outside.mean(), 1e-9)) if len(outside) else np.inf
                rows.append(("ZON-012", f"Z12-{i}-{tag}", L, H, act, exp, seg, 0,
                             "1h", d, tag))
                sharps.append(float(sh)); fvrs.append(float(fvr))
    zf = B.ztable(rows)
    zf["sharp"] = sharps
    zf["fvr"] = fvrs
    return zf


# ------------------------------------------------------------- condition helpers
def inside_history(ep):
    """zid -> sorted array of inside-contact T0 bar indexes."""
    ins = ep[ep["stratum"] == "inside"]
    return {z: np.sort(g["T0"].to_numpy()) for z, g in ins.groupby("zid")}


def fresh_mask(events, ep, cap_min):
    hist = inside_history(ep)
    ok = np.empty(len(events), bool)
    for k, e in enumerate(events.itertuples(index=False)):
        prior_inside = z_has_prior(hist, e.zid, e.T0)
        ok[k] = (e.age_min <= cap_min) and not prior_inside
    return ok


def z_has_prior(hist, zid, T0):
    arr = hist.get(zid)
    return arr is not None and arr[0] < T0


def isolation_mask(events, ev_mids, zones, D, thresh=0.5, exclude_ids=None):
    """No other ACTIVE parent-family zone midpoint within thresh*ADR at touch.

    ev_mids: midpoint of the touched object per event (real zone or shadow strip).
    exclude_ids: per-event zid to treat as 'self' (real zid, or shadow's parent zid).
    """
    zmid = ((zones["L"] + zones["H"]) / 2).to_numpy()
    zact = zones["act"].to_numpy(); zexp = zones["exp"].to_numpy()
    zid = zones["zid"].to_numpy()
    byday = B.zones_by_day(zones, D)
    ok = np.empty(len(events), bool)
    for k, e in enumerate(events.itertuples(index=False)):
        a = D.adr[e.day]
        cand = byday.get(int(e.day), [])
        iso = True
        for ci in cand:
            if exclude_ids is not None and zid[ci] == exclude_ids[k]:
                continue
            if zact[ci] <= e.t0_ns < zexp[ci] and abs(zmid[ci] - ev_mids[k]) < thresh * a:
                iso = False
                break
        ok[k] = iso
    return ok


def mids_for(events, zones):
    zm = zones.set_index("zid")
    return ((zm.loc[events["zid"], "L"].to_numpy()
             + zm.loc[events["zid"], "H"].to_numpy()) / 2)


def shadow_parent(zids):
    return [z.rsplit("-S", 1)[0] for z in zids]


def defended_touch2(ep):
    """touch-2 pre-break events whose zone's episode-1 was a CLEAN DEFENSE
    (rejW AND depth_end < 0.5) — all decided before touch 2."""
    sided = ep[ep["side"] != 0]
    e1 = sided[sided["touch_idx"] == 1].set_index("zid")
    t2 = sided[(sided["touch_idx"] == 2) & (sided["stratum"] == "pre")]
    keep = []
    for k, e in enumerate(t2.itertuples(index=False)):
        if e.zid in e1.index:
            r = e1.loc[e.zid]
            if isinstance(r, pd.DataFrame):
                r = r.iloc[0]
            if r["rejW"] == 1 and np.isfinite(r["depth_end"]) and r["depth_end"] < 0.5:
                keep.append(k)
    return t2.iloc[keep].reset_index(drop=True)


